"""
test_live_market_data.py
------------------------
Unit tests for the Live Market Data foundation subsystem:
- Provider abstraction and demo implementation
- 50 NIFTY constituent loading from metadata
- Asia/Kolkata timezone handling
- 14 required field verification
- DEMO DATA labeling enforcement
- Data validation and logical invariant checks
- Duplicate quote detection
- Storage persistence (snapshot & history)
- Real provider configuration and no-fake-data enforcement
"""

import unittest
from datetime import datetime, timedelta
from pathlib import Path
from zoneinfo import ZoneInfo
import pandas as pd

from src.live.models import MarketQuote, KOLKATA_TZ
from src.live.base import BaseLiveMarketDataProvider, determine_market_status
from src.live.demo_provider import DemoMarketDataProvider
from src.live.real_provider import (
    RealMarketDataProvider,
    RealMarketDataConfigurationError,
    RealMarketDataConnectionError
)
from src.live.validator import LiveQuoteValidator
from src.live.storage import LiveQuoteStorage
from src.live.service import LiveMarketDataService
from config.live_config import CONSTITUENTS_CSV


class TestLiveMarketDataFoundation(unittest.TestCase):
    """Test suite covering the live market data foundation components."""

    @classmethod
    def setUpClass(cls):
        cls.demo_provider = DemoMarketDataProvider(constituents_file=CONSTITUENTS_CSV, drift_seed=42)
        cls.validator = LiveQuoteValidator()
        cls.test_storage_dir = Path("data/test_live_tmp")
        cls.storage = LiveQuoteStorage(
            storage_dir=cls.test_storage_dir,
            snapshot_file=cls.test_storage_dir / "test_snapshot.csv",
            history_parquet=cls.test_storage_dir / "test_history.parquet",
            history_csv=cls.test_storage_dir / "test_history.csv"
        )
        cls.service = LiveMarketDataService(
            provider=cls.demo_provider,
            validator=cls.validator,
            storage=cls.storage
        )

    @classmethod
    def tearDownClass(cls):
        # Cleanup temporary test files
        if cls.test_storage_dir.exists():
            for f in cls.test_storage_dir.glob("*"):
                try:
                    f.unlink()
                except Exception:
                    pass
            try:
                cls.test_storage_dir.rmdir()
            except Exception:
                pass

    def test_01_constituents_loaded_from_metadata(self):
        """Verifies exactly 50 NIFTY constituent companies are loaded from metadata CSV."""
        self.assertTrue(CONSTITUENTS_CSV.exists(), f"Missing metadata file: {CONSTITUENTS_CSV}")
        constituents = self.service.get_constituents()
        self.assertEqual(len(constituents), 50, f"Expected 50 constituents, found {len(constituents)}")
        symbols = [c["symbol"] for c in constituents]
        self.assertIn("RELIANCE", symbols)
        self.assertIn("TCS", symbols)
        self.assertIn("HDFCBANK", symbols)
        self.assertIn("INFY", symbols)

    def test_02_all_14_required_fields_present(self):
        """Verifies that all 14 mandatory fields are supported and populated on quotes."""
        quote = self.demo_provider.get_quote("RELIANCE")
        self.assertIsNotNone(quote)

        q_dict = quote.to_dict()
        required_fields = [
            "Symbol", "Company", "Timestamp", "Open", "High", "Low",
            "Current Price", "Previous Close", "Change", "Change %",
            "Volume", "Day High", "Day Low", "Market Status"
        ]
        for field in required_fields:
            self.assertIn(field, q_dict, f"Missing mandatory field '{field}' in quote dict")
            self.assertIsNotNone(q_dict[field], f"Mandatory field '{field}' is None")

    def test_03_timestamp_asia_kolkata_timezone(self):
        """Verifies that timestamps strictly adhere to the Asia/Kolkata timezone (+05:30)."""
        quote = self.demo_provider.get_quote("TCS")
        self.assertIsNotNone(quote.timestamp.tzinfo)
        # Check zone info string or offset
        iso_str = quote.timestamp.isoformat()
        self.assertTrue(
            "+05:30" in iso_str or "Kolkata" in str(quote.timestamp.tzinfo),
            f"Timestamp does not have Asia/Kolkata offset: {iso_str}"
        )

    def test_04_demo_mode_clearly_labelled(self):
        """Verifies DEMO mode quotes are strictly labeled with is_demo=True and data_source='DEMO DATA'."""
        quote = self.demo_provider.get_quote("INFY")
        self.assertTrue(quote.is_demo, "Quote generated by Demo provider must have is_demo=True")
        self.assertEqual(quote.data_source, "DEMO DATA")
        self.assertTrue(quote.market_status.startswith("DEMO ("), "market_status must indicate DEMO context")

    def test_05_demo_provider_fetches_all_50_stocks(self):
        """Verifies DemoMarketDataProvider generates quotes for all 50 constituent stocks."""
        quotes = self.demo_provider.get_quotes()
        self.assertEqual(len(quotes), 50, f"Expected 50 quotes, got {len(quotes)}")
        symbols = [q.symbol for q in quotes]
        self.assertEqual(len(set(symbols)), 50, "All 50 symbols must be unique")

    def test_06_price_positivity_and_logical_invariants(self):
        """Validates that price fields are positive and obey OHLC logical relationships."""
        quotes = self.demo_provider.get_quotes()
        for q in quotes:
            is_valid, errors = self.validator.validate_quote(q)
            self.assertTrue(is_valid, f"Logical validation failed for {q.symbol}: {errors}")
            self.assertGreater(q.open, 0)
            self.assertGreater(q.current_price, 0)
            self.assertGreater(q.previous_close, 0)
            self.assertGreater(q.day_high, 0)
            self.assertGreater(q.day_low, 0)
            self.assertGreaterEqual(q.volume, 0)
            self.assertGreaterEqual(q.day_high, q.day_low)
            self.assertGreaterEqual(q.day_high, max(q.open, q.current_price))
            self.assertLessEqual(q.day_low, min(q.open, q.current_price))

    def test_07_validator_detects_violations(self):
        """Ensures validator catches negative prices, future timestamps, and inverted day high/low."""
        now = datetime.now(KOLKATA_TZ)

        # 1. Negative price
        bad_price = MarketQuote(
            symbol="TEST", company="Test Corp", timestamp=now,
            open=-50.0, high=100.0, low=40.0, current_price=90.0, previous_close=80.0,
            change=10.0, change_pct=12.5, volume=1000, day_high=100.0, day_low=40.0,
            market_status="OPEN"
        )
        valid, errs = self.validator.validate_quote(bad_price)
        self.assertFalse(valid)
        self.assertTrue(any("open" in e for e in errs))

        # 2. Inverted Day High < Day Low
        bad_bounds = MarketQuote(
            symbol="TEST", company="Test Corp", timestamp=now,
            open=100.0, high=80.0, low=110.0, current_price=95.0, previous_close=90.0,
            change=5.0, change_pct=5.56, volume=1000, day_high=80.0, day_low=110.0,
            market_status="OPEN"
        )
        valid, errs = self.validator.validate_quote(bad_bounds)
        self.assertFalse(valid)
        self.assertTrue(any("Day High" in e for e in errs))

        # 3. Far future timestamp (beyond clock skew)
        future_ts = now + timedelta(days=5)
        bad_time = MarketQuote(
            symbol="TEST", company="Test Corp", timestamp=future_ts,
            open=100.0, high=110.0, low=95.0, current_price=105.0, previous_close=100.0,
            change=5.0, change_pct=5.0, volume=1000, day_high=110.0, day_low=95.0,
            market_status="OPEN"
        )
        valid, errs = self.validator.validate_quote(bad_time)
        self.assertFalse(valid)
        self.assertTrue(any("future" in e for e in errs))

    def test_08_duplicate_detection(self):
        """Verifies duplicate checking identifies and filters identical quotes."""
        val = LiveQuoteValidator()
        q = self.demo_provider.get_quote("SBIN")
        self.assertFalse(val.is_duplicate(q))

        val.register_quote(q)
        self.assertTrue(val.is_duplicate(q), "Identical quote must be detected as duplicate")

        # filter_and_validate should drop the duplicate on second run
        batch = [q, q]
        valid_quotes, dropped = val.filter_and_validate(batch)
        self.assertEqual(len(valid_quotes), 0)  # Already registered once
        self.assertEqual(len(dropped), 2)

    def test_09_storage_snapshot_and_history(self):
        """Verifies quotes are saved to snapshot CSV and history parquet with deduplication."""
        quotes = self.demo_provider.get_quotes(["HDFCBANK", "ICICIBANK", "KOTAKBANK"])
        paths = self.storage.save_quotes(quotes)

        self.assertTrue(self.storage.snapshot_file.exists())
        self.assertTrue(self.storage.history_parquet.exists())

        snap_df = self.storage.load_latest_snapshot()
        self.assertIsNotNone(snap_df)
        self.assertEqual(len(snap_df), 3)
        self.assertIn("HDFCBANK", snap_df["Symbol"].values)

        hist_df = self.storage.load_history()
        self.assertIsNotNone(hist_df)
        self.assertGreaterEqual(len(hist_df), 3)

    def test_10_real_provider_requires_credentials(self):
        """Verifies RealMarketDataProvider refuses to run without credentials and does not fake data."""
        with self.assertRaises(RealMarketDataConfigurationError):
            RealMarketDataProvider(api_key="", access_token="")

    def test_11_real_provider_no_fake_values_in_production(self):
        """Verifies RealMarketDataProvider fails safely on unbound socket instead of fabricating fake data."""
        real_prov = RealMarketDataProvider(api_key="test_api_key_demo", api_secret="test_secret")
        self.assertFalse(real_prov.is_demo, "Real provider is_demo must be False")
        with self.assertRaises(RealMarketDataConnectionError):
            real_prov.get_quote("RELIANCE")

    def test_12_service_facade_end_to_end(self):
        """Verifies LiveMarketDataService orchestrates fetching, validation, and storage cleanly."""
        quotes, dropped = self.service.fetch_quotes(symbols=["TCS", "INFY"], persist=True)
        self.assertEqual(len(quotes), 2)
        self.assertEqual(len(dropped), 0)

        info = self.service.get_provider_info()
        self.assertEqual(info["provider_name"], "DemoMockProvider")
        self.assertTrue(info["is_demo"])
        self.assertEqual(info["data_source"], "DEMO DATA")
        self.assertTrue(self.service.health_check())


if __name__ == "__main__":
    unittest.main()
