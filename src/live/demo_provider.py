"""
demo_provider.py
----------------
DEMO / MOCK Live Market Data Provider.
Generates realistic, logically consistent, and verifiable mock quotes
for all 50 NIFTY 50 constituent companies without requiring external API credentials.

MANDATORY RULES:
- All quotes generated by this provider are explicitly labeled with:
    is_demo = True
    data_source = "DEMO DATA"
    market_status = "DEMO (<STATUS>)"
- Constituent universe is strictly grounded in data/metadata/nifty50_constituents.csv.
- Baseline prices anchor on the historical market close to provide realistic numbers.
"""

from datetime import datetime
from pathlib import Path
from typing import Dict, List, Optional, Any
import math
import random
import pandas as pd

from src.live.base import BaseLiveMarketDataProvider, determine_market_status
from src.live.models import MarketQuote
from config.live_config import (
    CONSTITUENTS_CSV,
    KOLKATA_TZ
)
from config.project_config import (
    CLEANED_DATA_PARQUET,
    CLEANED_DATA_CSV,
    PREDICTIONS_CSV
)
from src.utilities.logger import get_logger

logger = get_logger("DemoLiveMarketProvider")

class DemoMarketDataProvider(BaseLiveMarketDataProvider):
    """
    Demo/Mock live market data provider for offline testing and development.
    Anchors on real historical prices for the 50 constituents and generates
    statistically and logically consistent simulated market ticks.
    """

    def __init__(
        self,
        constituents_file: Path = CONSTITUENTS_CSV,
        drift_seed: Optional[int] = None
    ):
        self._constituents_file = constituents_file
        self._seed = drift_seed
        self._constituents: Dict[str, Dict[str, str]] = {}
        self._baselines: Dict[str, Dict[str, float]] = {}
        self._tick_counter: int = 0

        self._load_constituents()
        self._load_baselines()

    @property
    def provider_name(self) -> str:
        return "DemoMockProvider"

    @property
    def is_demo(self) -> bool:
        return True

    def _load_constituents(self) -> None:
        """Loads official 50 NIFTY constituent symbols and company metadata."""
        if not self._constituents_file.exists():
            logger.error(f"Constituents file missing: {self._constituents_file}")
            raise FileNotFoundError(f"Missing constituents file at: {self._constituents_file}")

        df = pd.read_csv(self._constituents_file)
        for _, row in df.iterrows():
            sym = str(row["Symbol"]).strip()
            self._constituents[sym] = {
                "symbol": sym,
                "company": str(row.get("Company_Name", sym)).strip(),
                "industry": str(row.get("Industry", "")).strip(),
                "sector": str(row.get("Sector", "")).strip()
            }
        logger.info(f"Loaded {len(self._constituents)} constituents from {self._constituents_file}")

    def _load_baselines(self) -> None:
        """Loads baseline closing prices and typical volumes for all constituents."""
        # 1. Try predictions CSV
        if PREDICTIONS_CSV.exists():
            try:
                p_df = pd.read_csv(PREDICTIONS_CSV)
                for _, r in p_df.iterrows():
                    sym = str(r["Symbol"]).strip()
                    if sym in self._constituents:
                        self._baselines[sym] = {
                            "prev_close": float(r["Current_Price"]),
                            "avg_volume": 1_500_000
                        }
            except Exception as e:
                logger.warning(f"Could not load baselines from predictions CSV: {e}")

        # 2. Try cleaned parquet for precise volumes and prices
        if CLEANED_DATA_PARQUET.exists():
            try:
                c_df = pd.read_parquet(CLEANED_DATA_PARQUET)
                last_rows = c_df.sort_values("Date").groupby("Symbol").last()
                for sym, r in last_rows.iterrows():
                    sym_str = str(sym).strip()
                    if sym_str in self._constituents:
                        close_p = float(r.get("Adj_Close", r.get("Close", 1000.0)))
                        vol = int(r.get("Volume", 1_000_000))
                        self._baselines[sym_str] = {
                            "prev_close": close_p,
                            "avg_volume": max(10_000, vol)
                        }
            except Exception as e:
                logger.warning(f"Could not load baselines from cleaned parquet: {e}")

        # 3. Fallback default for any missing symbol
        for sym in self._constituents:
            if sym not in self._baselines:
                self._baselines[sym] = {"prev_close": 1500.0, "avg_volume": 1_000_000}

    def _generate_quote(self, symbol: str, now_ist: datetime) -> MarketQuote:
        """Generates a realistic, logically valid quote for a constituent."""
        meta = self._constituents.get(symbol, {"company": symbol})
        baseline = self._baselines.get(symbol, {"prev_close": 1000.0, "avg_volume": 1_000_000})

        prev_close = baseline["prev_close"]
        avg_vol = baseline["avg_volume"]

        # Deterministic variation seeded by symbol and tick counter / timestamp
        rng = random.Random(f"{symbol}_{self._tick_counter}_{now_ist.minute}" if self._seed is None else f"{symbol}_{self._seed}")
        
        # Intra-day drift percentage between -2.5% and +2.5%
        drift_pct = rng.uniform(-2.2, 2.2)
        open_offset_pct = rng.uniform(-0.6, 0.6)

        open_p = round(prev_close * (1.0 + open_offset_pct / 100.0), 2)
        curr_p = round(prev_close * (1.0 + drift_pct / 100.0), 2)

        # High must be >= max(open, current_price)
        max_seen = max(open_p, curr_p)
        min_seen = min(open_p, curr_p)

        day_high = round(max_seen * (1.0 + rng.uniform(0.1, 0.8) / 100.0), 2)
        day_low = round(min_seen * (1.0 - rng.uniform(0.1, 0.8) / 100.0), 2)

        # Invariant checks
        if day_high < max_seen:
            day_high = max_seen
        if day_low > min_seen:
            day_low = min_seen

        change = round(curr_p - prev_close, 2)
        change_pct = round((change / prev_close) * 100.0, 2)

        # Simulated volume with slight variation
        vol_factor = rng.uniform(0.85, 1.25)
        volume = int(avg_vol * vol_factor)

        base_status = determine_market_status(now_ist)
        market_status = f"DEMO ({base_status})"

        return MarketQuote(
            symbol=symbol,
            company=meta["company"],
            timestamp=now_ist,
            open=open_p,
            high=day_high,
            low=day_low,
            current_price=curr_p,
            previous_close=prev_close,
            change=change,
            change_pct=change_pct,
            volume=volume,
            day_high=day_high,
            day_low=day_low,
            market_status=market_status,
            is_demo=True,
            data_source="DEMO DATA"
        )

    def get_quote(self, symbol: str) -> Optional[MarketQuote]:
        """Fetches demo quote for a single symbol."""
        sym_clean = symbol.strip().upper()
        if sym_clean not in self._constituents:
            logger.warning(f"Symbol '{symbol}' not found in NIFTY 50 constituents.")
            return None

        self._tick_counter += 1
        now = datetime.now(KOLKATA_TZ)
        return self._generate_quote(sym_clean, now)

    def get_quotes(self, symbols: Optional[List[str]] = None) -> List[MarketQuote]:
        """
        Fetches demo quotes for the requested symbols or all 50 NIFTY constituents.
        All quotes are captured at the exact same Asia/Kolkata timestamp.
        """
        self._tick_counter += 1
        now = datetime.now(KOLKATA_TZ)

        target_symbols = (
            [s.strip().upper() for s in symbols]
            if symbols is not None
            else sorted(self._constituents.keys())
        )

        quotes = []
        for sym in target_symbols:
            if sym in self._constituents:
                quotes.append(self._generate_quote(sym, now))
            else:
                logger.warning(f"Skipping unknown constituent symbol: {sym}")

        return quotes

    def health_check(self) -> bool:
        """Demo provider is local and always operational."""
        return len(self._constituents) == 50
